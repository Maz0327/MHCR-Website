"""What GitHub Pages will publish, and the generated _config.yml that keeps everything else off it (stdlib only).

Rule (pre-launch QA, 10-15): no file may be served unless a generated page uses it. So the build lists every asset
(images/, css/, js/, fonts/) that no page references and writes it into _config.yml `exclude:`, next to the internal
docs. When a job is published later its photos become referenced and drop out of the list on the next build.
Jekyll never publishes paths that start with "_" or "." (so _build/ and .gitignore stay private).
"""
import os
import re
import subprocess

DOCS = ["AWARD-WINNING-SITE-ANALYSIS.md", "DESIGN-STANDARDS-RESEARCH.md", "MHCR-DESIGN-AUDIT.md", "PLACEHOLDER-GUIDE.md"]
ASSET_DIRS = ("images/", "css/", "js/", "fonts/")
URL_ATTR = re.compile(r'\s(?:src|href|srcset|imagesrcset|content)="([^"]+)"')
CSS_URL = re.compile(r"url\(\s*['\"]?([^'\")]+)['\"]?\s*\)")


def repo_files(site):
    """Files that are (or will be, once committed) in the repo: tracked + untracked-but-not-ignored."""
    try:
        out = subprocess.run(["git", "-C", site, "ls-files", "--cached", "--others", "--exclude-standard"],
                             capture_output=True, text=True, check=True).stdout
        return sorted({p for p in out.splitlines() if os.path.exists(os.path.join(site, p))})
    except (OSError, subprocess.CalledProcessError):
        return sorted(os.path.relpath(os.path.join(d, f), site) for d, _, fs in os.walk(site) for f in fs)


def published(files, exclude):
    """The subset Jekyll would publish: no _/. path parts, not excluded (file or folder)."""
    ex = [e.rstrip("/") for e in exclude]
    keep = []
    for p in files:
        if any(part.startswith(("_", ".")) for part in p.split("/")):
            continue
        if any(p == e or p.startswith(e + "/") for e in ex):
            continue
        keep.append(p)
    return keep


def referenced(pages, site_url, site):
    """Site paths used by the generated pages {path: html}: src/srcset/href/og:image URLs, plus url() inside used CSS."""
    refs = {}
    for path, text in pages.items():
        here = os.path.dirname(path)
        for raw in URL_ATTR.findall(text):
            for part in raw.split(","):
                u = part.strip().split(" ")[0] if part.strip() else ""
                if u.startswith(site_url + "/"):
                    target = u[len(site_url) + 1:].split("#")[0].split("?")[0]
                elif not u or re.match(r"^(?:#|[a-z][a-z0-9+.-]*:|//)", u, re.I):
                    continue
                else:
                    target = os.path.normpath(os.path.join(here, u.split("#")[0].split("?")[0])).replace(os.sep, "/")
                refs.setdefault(target, set()).add(path)
    for css in [r for r in list(refs) if r.endswith(".css") and os.path.exists(os.path.join(site, r))]:
        with open(os.path.join(site, css), encoding="utf-8") as f:
            for u in CSS_URL.findall(f.read()):
                if not re.match(r"^(?:data:|[a-z][a-z0-9+.-]*:|//)", u, re.I):
                    t = os.path.normpath(os.path.join(os.path.dirname(css), u)).replace(os.sep, "/")
                    refs.setdefault(t, set()).add(css)
    return refs


def unreferenced_assets(files, refs):
    """Assets no page uses. Font licence texts (fonts/*.txt) always ship with the fonts (OFL)."""
    return [p for p in files if p.startswith(ASSET_DIRS) and p not in refs and not re.fullmatch(r"fonts/[^/]+\.txt", p)]


def config_yml(exclude):
    lines = ["# GENERATED by _build/build.py (build_publish_list.py). Do not edit by hand.",
             "# GitHub Pages (Jekyll) publishes every file in the repo except paths that start with _ or . and the",
             "# paths below: internal docs, plus every image/css/js/font file that no generated page uses.", "exclude:"]
    return "\n".join(lines + [f"  - {e}" for e in exclude]) + "\n"
